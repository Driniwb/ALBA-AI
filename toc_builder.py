"""Word-only prototype for preparing the EU side of a ToC.

No AI, external transmission, legal assessment or translation is performed.
Only born-digital PDF and DOCX input are accepted. Extracted text may differ
from the source layout and must be manually verified against the original.
"""
from __future__ import annotations

from dataclasses import dataclass
from io import BytesIO
import re

from docx import Document
from docx.enum.section import WD_ORIENT
from docx.enum.table import WD_TABLE_ALIGNMENT, WD_CELL_VERTICAL_ALIGNMENT
from docx.shared import Cm, Pt

MAX_FILE_BYTES = 12 * 1024 * 1024
MAX_PAGES = 180
MAX_CHARS = 240_000
MAX_SECTIONS = 3000

ARTICLE_HEADING = re.compile(
    r"^(?:Article|Neni)\s+\d+[a-z]?(?:\s*[–-]\s*\d+[a-z]?)?\s*\.?\s*$",
    flags=re.IGNORECASE,
)
ANNEX_HEADING = re.compile(
    r"^(?:Annex|Aneksi|Aneks)\s+(?:[IVXLCDM]+|\d+|[A-Z])\s*\.?\s*$",
    flags=re.IGNORECASE,
)


@dataclass(frozen=True)
class Provision:
    reference: str
    text: str


@dataclass(frozen=True)
class Extracted:
    text: str
    warnings: tuple[str, ...]


def _clean_newlines(text: str) -> str:
    # Preserve all extracted characters except platform newline conventions.
    return text.replace("\r\n", "\n").replace("\r", "\n")


def extract_document(filename: str, data: bytes) -> Extracted:
    """Extract text without rewriting or summarising; raise on unsafe input."""
    if not filename or not isinstance(data, bytes) or not data:
        raise ValueError("Choose a non-empty PDF or DOCX document.")
    if len(data) > MAX_FILE_BYTES:
        raise ValueError("File exceeds the 12 MB limit.")

    name = filename.lower()
    warnings = []

    if name.endswith(".docx"):
        try:
            doc = Document(BytesIO(data))
        except Exception as exc:
            raise ValueError("Unable to open the Word document.") from exc

        parts = []
        # Preserve document body sequence; tables are flattened with a warning.
        for block in doc.iter_inner_content():
            if hasattr(block, "rows"):
                warnings.append(
                    "The directive contains tables. Their cells are flattened; "
                    "verify every row against the source."
                )
                for row in block.rows:
                    parts.append("\t".join(cell.text for cell in row.cells))
            else:
                parts.append(block.text)
                if block._p.pPr is not None and block._p.pPr.numPr is not None:
                    warnings.append(
                        "Some list numbers are generated by Word and may not "
                        "appear in the extracted text."
                    )
        text = "\n".join(parts)
    elif name.endswith(".pdf"):
        from pypdf import PdfReader
        try:
            pdf = PdfReader(BytesIO(data), strict=False)
            if pdf.is_encrypted:
                raise ValueError("Encrypted PDFs are not supported.")
            if len(pdf.pages) > MAX_PAGES:
                raise ValueError("PDF exceeds the 180-page limit.")
            pages = [(page.extract_text() or "") for page in pdf.pages]
        except ValueError:
            raise
        except Exception as exc:
            raise ValueError("Unable to read the PDF's text layer.") from exc
        text = "\n\n".join(pages)
        warnings.append(
            "PDF extraction may alter line wrapping, ordering or footnotes. "
            "Verify the source text before using the table."
        )
        if any(not page.strip() for page in pages):
            warnings.append(
                "At least one PDF page has no extractable text; check for scans "
                "or image-only pages."
            )
    else:
        raise ValueError("Only .docx and text-based .pdf are supported.")

    text = _clean_newlines(text)
    if not text.strip():
        raise ValueError(
            "No extractable text. Scanned PDFs require OCR, not available here."
        )
    if len(text) > MAX_CHARS:
        raise ValueError("Document exceeds the 240,000-character limit.")
    return Extracted(text=text, warnings=tuple(dict.fromkeys(warnings)))



# PDF page identifiers in the consolidated layout are not legal text.
# Optional cleanup must be requested by the user and remains subject to review.
PDF_PAGE_MARKER = re.compile(
    r"(?:▼[A-Z]\s*)?\b0\d{4}[A-Z]\d{4}\s*—\s*[A-Z]{2}\s*—\s*"
    r"\d{2}\.\d{2}\.\d{4}\s*—\s*[\d.]+\s*—\s*\d{1,4}\b",
    flags=re.UNICODE,
)


def pdf_extraction_flags(text: str) -> list[str]:
    """Detect high-risk PDF layout artefacts; not a legal text validator."""
    issues = []
    if PDF_PAGE_MARKER.search(text):
        issues.append("U gjetën shënime botimi/numra faqesh brenda dispozitave.")
    if "\u00ad" in text:
        issues.append("U gjetën ndarje fjalësh (soft hyphen) nga PDF-ja.")
    return issues


def normalise_pdf_display(text: str) -> str:
    """Optional mechanical *display* cleanup, not a verified transcription.

    Apply ONLY after segmentation into legal units. Does not translate,
    paraphrase or create legal structure. The original PDF remains authoritative.
    """
    cleaned = PDF_PAGE_MARKER.sub("", text)
    cleaned = re.sub(r"(?<=\w)\s*\u00ad\s*(?=\w)", "", cleaned)
    cleaned = cleaned.replace("\u00ad", "")
    cleaned = re.sub(r"[ \t]*\n[ \t]*", " ", cleaned)
    cleaned = re.sub(r" {2,}", " ", cleaned)
    return cleaned.strip()

def split_provisions(text: str) -> list[Provision]:
    """Make Article/Annex rows, retaining preamble and all extracted text.

    This MVP intentionally does NOT split paragraphs (1., 2.) or lettered
    points: guessing where they start risks altering legal references.
    """
    if not text.strip():
        raise ValueError("No text to structure.")
    lines = _clean_newlines(text).split("\n")
    starts = []
    for i, line in enumerate(lines):
        heading = line.strip()
        if ARTICLE_HEADING.fullmatch(heading) or ANNEX_HEADING.fullmatch(heading):
            starts.append((i, heading))

    rows = []
    if not starts:
        return [Provision("Unstructured source text — manual review", text)]

    if starts[0][0] > 0:
        intro = "\n".join(lines[: starts[0][0]])
        if intro.strip():
            rows.append(Provision("Introductory text / recitals", intro))

    for k, (start, name) in enumerate(starts):
        end = starts[k + 1][0] if k + 1 < len(starts) else len(lines)
        segment = "\n".join(lines[start:end])
        if segment.strip():
            rows.append(Provision(name, segment))
    if len(rows) > MAX_SECTIONS:
        raise ValueError("More than 3,000 sections detected; split the source.")
    return rows


def to_word(provisions: list[Provision], source_name: str = "") -> bytes:
    """Generate a review-ready 4-column Word ToC with two blank columns."""
    if not provisions:
        raise ValueError("No provisions to export.")
    doc = Document()
    section = doc.sections[0]
    section.orientation = WD_ORIENT.LANDSCAPE
    section.page_width, section.page_height = Cm(29.7), Cm(21.0)
    section.left_margin = section.right_margin = Cm(1.5)
    section.top_margin = section.bottom_margin = Cm(1.5)

    normal = doc.styles["Normal"]
    normal.font.name = "Aptos"
    normal.font.size = Pt(9)

    heading = doc.add_heading("Table of Concordance – draft for legal review", 1)
    heading.style.font.size = Pt(13)
    doc.add_paragraph(
        "Source: " + (source_name or "uploaded EU text") +
        " | Extracted text; not a verified legal transcription."
    )
    doc.add_paragraph(
        "National provisions and Remarks are intentionally left blank. "
        "Original text, references, paragraph numbering and annexes must "
        "be checked against the official publication."
    )

    table = doc.add_table(rows=1, cols=4)
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    widths = [Cm(3), Cm(13), Cm(6.0), Cm(4.6)]
    headers = [
        "EU provision",
        "Text of the EU provision (extracted)",
        "National provision",
        "Remarks",
    ]

    for i, (header, width) in enumerate(zip(headers, widths)):
        cell = table.rows[0].cells[i]
        cell.text = header
        cell.width = width
        cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
        for run in cell.paragraphs[0].runs:
            run.bold = True
    # Repeat heading row over pages.
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    trPr = table.rows[0]._tr.get_or_add_trPr()
    repeat = OxmlElement("w:tblHeader")
    repeat.set(qn("w:val"), "true")
    trPr.append(repeat)

    for p in provisions:
        cells = table.add_row().cells
        cells[0].text = p.reference
        cells[1].text = p.text
        cells[2].text = ""
        cells[3].text = ""
        for i, width in enumerate(widths):
            cells[i].width = width
            cells[i].vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.TOP

    out = BytesIO()
    doc.save(out)
    return out.getvalue()
