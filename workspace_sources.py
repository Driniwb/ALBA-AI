"""Official links provided by the user, for the optional ALBA sources panel.

These are *references*, not independently retrieved or verified legal acts.
The chat UI never turns links generated by an AI reply into verified sources.
"""
from __future__ import annotations

import re
from urllib.parse import parse_qs, urlsplit

_SOURCE_URL = re.compile(r"https://[^\s<>\"'\u201c\u201d]+", re.IGNORECASE)
_OFFICIAL = {
    "qbz.gov.al": "QBZ",
    "www.qbz.gov.al": "QBZ",
    "eur-lex.europa.eu": "EUR-Lex",
}
_TRAILING = ".,;:!?]>)}"


def official_link(url: str) -> dict[str, str] | None:
    """Accept a direct official document reference, never a similar-looking host."""
    if not isinstance(url, str):
        return None
    candidate = url.strip().rstrip(_TRAILING)
    try:
        parsed = urlsplit(candidate)
        allowed_port = parsed.port in (None, 443)
    except ValueError:
        return None
    if (parsed.scheme != "https" or parsed.hostname not in _OFFICIAL
            or parsed.username or parsed.password or not allowed_port
            or parsed.fragment or len(candidate) > 900):
        return None
    if parsed.hostname in {"qbz.gov.al", "www.qbz.gov.al"}:
        if not parsed.path.startswith("/eli/"):
            return None
        if parsed.query:
            return None
        label = "QBZ · Akt i referuar"
    else:
        if not (parsed.path.startswith("/legal-content/")
                or parsed.path.startswith("/eli/")):
            return None
        celex = parse_qs(parsed.query).get("uri", [""])[0]
        if celex.startswith("CELEX:") and len(celex) <= 36:
            label = "EUR-Lex · " + celex
        else:
            label = "EUR-Lex · Akt i referuar"
    return {"url": candidate, "label": label, "source": _OFFICIAL[parsed.hostname]}


def user_source_links(messages: list[dict], *, limit: int = 8) -> list[dict[str, str]]:
    """Return only official links explicitly present in user turns.

    This is a display-only extraction. It never establishes link availability,
    up-to-dateness, legal status, or reliability of an uploaded document.
    """
    found: list[dict[str, str]] = []
    seen: set[str] = set()
    for item in reversed(messages):
        if item.get("role") != "user" or not isinstance(item.get("content"), str):
            continue
        for raw in _SOURCE_URL.findall(item["content"]):
            link = official_link(raw)
            if link is not None and link["url"] not in seen:
                found.append(link)
                seen.add(link["url"])
                if len(found) >= limit:
                    return found
    return found


_DOCUMENT_EXCERPT = re.compile(
    r"\[PUBLIC DOCUMENT EXCERPT:\s*([^\]\n]{1,160})\]\n"
)


def user_document_excerpts(
    messages: list[dict], *, limit: int = 8
) -> list[str]:
    """List labels of excerpts provided in this chat; no file-index claims.

    This returns only user message labels. Binary documents are not persisted
    by this helper and no document content is independently verified.
    """
    names: list[str] = []
    observed: set[str] = set()
    for item in reversed(messages):
        if item.get("role") != "user" or not isinstance(item.get("content"), str):
            continue
        for name in _DOCUMENT_EXCERPT.findall(item["content"]):
            cleaned = name.strip()
            if cleaned and cleaned not in observed:
                names.append(cleaned)
                observed.add(cleaned)
                if len(names) >= limit:
                    return names
    return names


# The backend appends these exact headings after its attempt to read official
# source content. This is a source-trace display, NOT authentication of the
# current legal status or a substitute for article-level citation checking.
_RESEARCH_TRACE_HEADING = "**Official source trace (read-only; not a legal-status certificate)**"
_RESEARCH_ENTRY_HEADING = "**Official entry points (text not independently retrieved)**"
_TRACE_LINE = re.compile(r"^\s*-\s*\[([^\]\n]{1,160})\]\((https://[^)\s]+)\)")


def assistant_research_sources(
    messages: list[dict], *, limit: int = 8
) -> list[dict[str, str]]:
    """Read only explicit, appended source-trace blocks from assistant turns.

    An official URL must still pass exact-host checks. The returned labels
    disclose whether the text was reportedly fetched or only linked.
    """
    found, seen = [], set()
    for item in reversed(messages):
        if item.get("role") != "assistant":
            continue
        content = item.get("content", "")
        if not isinstance(content, str):
            continue
        verified = content.rfind(_RESEARCH_TRACE_HEADING)
        navigational = content.rfind(_RESEARCH_ENTRY_HEADING)
        if max(verified, navigational) < 0:
            continue
        is_read = verified > navigational
        index = verified if is_read else navigational
        block = content[index:].split("\n\n---", 1)[0]
        for line in block.splitlines():
            match = _TRACE_LINE.match(line)
            if not match:
                continue
            title, url = match.groups()
            # The source link is a presentation record, not a network grant.
            known = official_link(url)
            if known is None:
                from urllib.parse import urlsplit
                parsed = urlsplit(url)
                if (parsed.scheme != "https" or parsed.hostname not in {
                    "qbz.gov.al", "www.qbz.gov.al",
                } or not parsed.path.startswith("/alfresco/webdav/Aktet/")
                    or not parsed.path.lower().endswith(".pdf")
                    or parsed.query or parsed.fragment or parsed.username):
                    continue
            if url in seen:
                continue
            found.append({
                "label": title,
                "url": url,
                "status": "text retrieved" if is_read else "link only",
            })
            seen.add(url)
            if len(found) >= limit:
                return found
    return found
