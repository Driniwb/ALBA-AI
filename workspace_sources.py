"""Official links provided by the user, for the optional ALBA sources panel.

These are *references*, not independently retrieved or verified legal acts.
The chat UI never turns links generated by an AI reply into verified sources.
"""
from __future__ import annotations

import re
from urllib.parse import parse_qs, urlsplit

_SOURCE_URL = re.compile(r"https://[^\s<>\"'\u201c\u201d]+", re.IGNORECASE)
_OFFICIAL = {
    "qbz.gov.al": "QBZ",
    "www.qbz.gov.al": "QBZ",
    "eur-lex.europa.eu": "EUR-Lex",
}
_TRAILING = ".,;:!?]>)}"


def official_link(url: str) -> dict[str, str] | None:
    """Accept a direct official document reference, never a similar-looking host."""
    if not isinstance(url, str):
        return None
    candidate = url.strip().rstrip(_TRAILING)
    try:
        parsed = urlsplit(candidate)
        allowed_port = parsed.port in (None, 443)
    except ValueError:
        return None
    if (parsed.scheme != "https" or parsed.hostname not in _OFFICIAL
            or parsed.username or parsed.password or not allowed_port
            or parsed.fragment or len(candidate) > 900):
        return None
    if parsed.hostname in {"qbz.gov.al", "www.qbz.gov.al"}:
        if not parsed.path.startswith("/eli/"):
            return None
        if parsed.query:
            return None
        label = "QBZ · Akt i referuar"
    else:
        if not (parsed.path.startswith("/legal-content/")
                or parsed.path.startswith("/eli/")):
            return None
        celex = parse_qs(parsed.query).get("uri", [""])[0]
        if celex.startswith("CELEX:") and len(celex) <= 36:
            label = "EUR-Lex · " + celex
        else:
            label = "EUR-Lex · Akt i referuar"
    return {"url": candidate, "label": label, "source": _OFFICIAL[parsed.hostname]}


def user_source_links(messages: list[dict], *, limit: int = 8) -> list[dict[str, str]]:
    """Return only official links explicitly present in user turns.

    This is a display-only extraction. It never establishes link availability,
    up-to-dateness, legal status, or reliability of an uploaded document.
    """
    found: list[dict[str, str]] = []
    seen: set[str] = set()
    for item in reversed(messages):
        if item.get("role") != "user" or not isinstance(item.get("content"), str):
            continue
        for raw in _SOURCE_URL.findall(item["content"]):
            link = official_link(raw)
            if link is not None and link["url"] not in seen:
                found.append(link)
                seen.add(link["url"])
                if len(found) >= limit:
                    return found
    return found
